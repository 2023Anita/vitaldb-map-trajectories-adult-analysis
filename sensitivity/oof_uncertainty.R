args <- commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==3L, !file.exists(args[3]))
p <- read.csv(args[1], stringsAsFactors=FALSE)
d <- read.csv(args[2], stringsAsFactors=FALSE)
stopifnot(nrow(d)==5501L, !anyDuplicated(d$caseid), is.numeric(d$age), all(is.finite(d$age)), all(d$age>=18))
keys <- unique(p[,c('caseid','subjectid','y')])
check <- merge(keys,d[,c('caseid','subjectid','icu_use')],by=c('caseid','subjectid'))
stopifnot(nrow(keys)==nrow(d),nrow(check)==nrow(d),all(check$y==check$icu_use))
models <- unique(p$model); ids <- unique(p$subjectid)
n_cases <- length(unique(p$caseid))
stopifnot(length(models)==5L, n_cases>0L, nrow(p)==n_cases*5L, all(table(p$model)==n_cases))
wide <- reshape(p[,c("caseid","subjectid","y","model","p")], idvar=c("caseid","subjectid","y"), timevar="model", direction="wide")
stopifnot(nrow(wide)==n_cases, !anyNA(wide))
auc <- function(y, x) { r<-rank(x,ties.method="average"); n<-sum(y==1); m<-sum(y==0); if(n==0||m==0) return(NA_real_); (sum(r[y==1])-n*(n+1)/2)/(n*m) }
names_models <- sub("^p\\.","",grep("^p\\.",names(wide),value=TRUE))
groups <- split(seq_len(nrow(wide)), wide$subjectid)
set.seed(20261103)
out <- matrix(NA_real_, 500, length(names_models), dimnames=list(NULL,names_models))
for(i in seq_len(nrow(out))) { ix<-unlist(groups[as.character(sample(ids,length(ids),replace=TRUE))],use.names=FALSE); for(m in names_models) out[i,m]<-auc(wide$y[ix],wide[[paste0("p.",m)]][ix]) }
result <- do.call(rbind,lapply(names_models,function(m) { delta<-out[,m]-out[,"base"]; data.frame(model=m, auroc_low=quantile(out[,m],.025,na.rm=TRUE),auroc_high=quantile(out[,m],.975,na.rm=TRUE),delta_vs_base_low=quantile(delta,.025,na.rm=TRUE),delta_vs_base_high=quantile(delta,.975,na.rm=TRUE),reps=sum(is.finite(delta))) }))
write.csv(result,args[3],row.names=FALSE)
print(result)
